import { useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { api } from '../api';
import { MediaPreview } from '../components/MediaPreview';
import { StatusBadge } from '../components/StatusBadge';
import { formatBytes, formatDate, formatDuration, PLATFORM_LABELS } from '../format';
import { ACTIVE_STATUSES, Job } from '../types';

const POLL_MS = 2000;

function CaptionCard({ caption }: { caption: NonNullable<Job['caption']> }) {
  const [copied, setCopied] = useState(false);
  const full = `${caption.text}\n\n${caption.hashtags.join(' ')}`;
  const copy = async () => {
    await navigator.clipboard.writeText(full);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };
  return (
    <div className="card caption">
      <div className="row between">
        <h3>Caption</h3>
        <button className="btn ghost small" onClick={copy}>
          {copied ? 'Copied' : 'Copy'}
        </button>
      </div>
      <p>{caption.text}</p>
      <p className="hashtags">{caption.hashtags.join(' ')}</p>
      {caption.simulated && <small className="muted">Generated by the simulated AI provider.</small>}
    </div>
  );
}

export function JobPage() {
  const { id = '' } = useParams();
  const queryClient = useQueryClient();
  const jobQuery = useQuery({
    queryKey: ['job', id],
    queryFn: () => api.getJob(id),
    refetchInterval: (query) => (query.state.data && ACTIVE_STATUSES.includes(query.state.data.status) ? POLL_MS : false),
  });

  const onJob = (job: Job) => {
    queryClient.setQueryData(['job', id], job);
    void queryClient.invalidateQueries({ queryKey: ['jobs'] });
  };
  const retry = useMutation({ mutationFn: () => api.retryJob(id), onSuccess: onJob });
  const cancel = useMutation({ mutationFn: () => api.cancelJob(id), onSuccess: onJob });

  if (jobQuery.isLoading) return <div className="center muted">Loading job…</div>;
  if (jobQuery.error) return <p className="error">{jobQuery.error.message}</p>;
  const job = jobQuery.data!;
  const active = ACTIVE_STATUSES.includes(job.status);
  const actionError = retry.error ?? cancel.error;

  return (
    <div className="stack">
      <div className="row between wrap">
        <div className="stack small-gap">
          <h1>
            {PLATFORM_LABELS[job.platform]} · {job.preset.label}
          </h1>
          <span className="muted">
            {job.preset.width}×{job.preset.height} ({job.preset.aspectRatio}) · created {formatDate(job.createdAt)}
          </span>
        </div>
        <StatusBadge status={job.status} />
      </div>

      {active && (
        <div className="card">
          <div className="row between">
            <span className="stage">{job.stage}…</span>
            <span className="muted">{job.progress}%</span>
          </div>
          <div className="progress">
            <div style={{ width: `${job.progress}%` }} />
          </div>
          <div className="row between">
            <small className="muted">
              Attempt {Math.max(job.attempts, 1)} of {job.maxAttempts}
            </small>
            <button className="btn ghost small" onClick={() => cancel.mutate()} disabled={cancel.isPending}>
              Cancel
            </button>
          </div>
        </div>
      )}

      {job.status === 'failed' && job.error && (
        <div className="card danger">
          <strong>Generation failed</strong>
          <p>{job.error.message}</p>
          <small className="muted">
            {job.error.code} · after {job.attempts} attempt{job.attempts === 1 ? '' : 's'}
          </small>
        </div>
      )}

      {(job.status === 'failed' || job.status === 'cancelled') && (
        <div>
          <button className="btn primary" onClick={() => retry.mutate()} disabled={retry.isPending}>
            Retry
          </button>
        </div>
      )}
      {actionError && <p className="error">{actionError.message}</p>}

      <div className="result-grid">
        {job.output ? (
          <div className="stack">
            <h3>Output</h3>
            <MediaPreview
              kind="video"
              url={job.output.url}
              poster={job.thumbnailUrl}
              width={job.output.width}
              height={job.output.height}
              label="Generated video"
            />
            <div className="row between wrap">
              <span className="muted">
                {formatDuration(job.output.durationSeconds)} · {formatBytes(job.output.size)}
              </span>
              <a className="btn primary" href={job.output.downloadUrl} download>
                Download MP4
              </a>
            </div>
          </div>
        ) : (
          job.status === 'completed' && <p className="muted">The output has expired.</p>
        )}

        <div className="stack">
          {job.caption && <CaptionCard caption={job.caption} />}
          {job.input && (
            <div className="stack">
              <h3>Source</h3>
              <div className="source-preview">
                <MediaPreview
                  kind={job.input.kind}
                  url={job.input.url}
                  width={job.input.width}
                  height={job.input.height}
                  label={job.input.originalName}
                />
              </div>
              <small className="muted truncate">{job.input.originalName}</small>
            </div>
          )}
        </div>
      </div>

      <Link to="/" className="btn ghost">
        Create another
      </Link>
    </div>
  );
}
